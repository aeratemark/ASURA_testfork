"""Exporters: from the editor's profile to what ASURA can (or will) consume.

* ``asura_sql``   - **works with ASURA today**: rewrites ``map_spawn`` rows and the ``map_config`` default
  spawn for every map in the profile (the tables ``asura-world`` reads at start-up). Apply it with
  ``psql`` or ASURA's ``tools/seed-map.ps1`` flow.
* ``content_json`` - one self-describing JSON bundle of the whole profile (agents, placements, routes,
  dialogue, quests, scripts inline). For a future ASURA loader; JSON is the exchange format ASURA's
  docs lean towards but have not selected.
* ``lua_bundle``  - the same content as a Lua table module plus the scripts, for a loader that wants
  to read content through the embedded Lua runtime.

Add your own with ``@exporter("name", "Label", ".ext")``.
"""

from __future__ import annotations

import json
from dataclasses import fields
from pathlib import Path
from typing import Callable

from ..content.model import Profile
from ..content.store import dialogue_to_dict, map_to_dict, quest_to_dict, _record_to_dict

EXPORTERS: dict[str, tuple[str, str, Callable[[Profile, Path], list[Path]]]] = {}


def exporter(key: str, label: str, suffix: str):
    def deco(fn):
        EXPORTERS[key] = (label, suffix, fn)
        return fn
    return deco


def _sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def _num(v: float) -> str:
    return repr(float(v))


MAP_PORTAL_DDL = """CREATE TABLE IF NOT EXISTS map_portal (
    map_id int NOT NULL, idx int NOT NULL, x real NOT NULL, y real NOT NULL, to_map int NULL,
    arrive_x real NULL, arrive_y real NULL, source text NOT NULL DEFAULT '',
    PRIMARY KEY (map_id, idx), CHECK ((arrive_x IS NULL) = (arrive_y IS NULL)));"""


def portal_sql(mid: int, m) -> list[str]:
    from ..content.model import TravelPortal
    portals = [o for o in m.objects if isinstance(o, TravelPortal)]
    lines = [f"DELETE FROM map_portal WHERE map_id = {mid};"]
    for i, p in enumerate(portals):
        to = str(int(p.to_map)) if p.to_map else "NULL"
        arrive = (f"{_num(p.arrive_x)}, {_num(p.arrive_y)}" if p.to_map and (p.arrive_x or p.arrive_y)
                  else "NULL, NULL")
        source = p.source or "editor"
        lines.append(f"INSERT INTO map_portal (map_id, idx, x, y, to_map, arrive_x, arrive_y, source) VALUES "
                     f"({mid}, {i}, {_num(p.x)}, {_num(p.y)}, {to}, {arrive}, {_sql_str(source)});")
    return lines


@exporter("asura_sql", "ASURA SQL: spawn points and portals (map_spawn / map_config / map_portal)", ".sql")
def export_sql(profile: Profile, out: Path, map_ids: list[int] | None = None) -> list[Path]:
    lines = [
        f"-- Generated by ASURA Construction Set from profile {profile.id!r} ({profile.name}).",
        "-- Rewrites the spawn points and travel portals of the maps below. Safe to re-run.",
        "BEGIN;",
        MAP_PORTAL_DDL,
    ]
    from ..content.scope import in_scope
    for mid, m in sorted(profile.maps.items()):
        spawns = m.spawns()
        if not in_scope(mid) or (map_ids is not None and mid not in map_ids):
            continue
        lines.append(f"\n-- {m.label()}")
        lines += portal_sql(mid, m)
        if not spawns:
            continue
        lines.append(f"DELETE FROM map_spawn WHERE map_id = {mid};")
        for i, s in enumerate(spawns):
            lines.append(f"INSERT INTO map_spawn (map_id, idx, x, y, plane) VALUES "
                         f"({mid}, {i}, {_num(s.x)}, {_num(s.y)}, {int(s.plane)});")
        s0 = spawns[0]
        lines.append(f"UPDATE map_config SET spawn_count = {len(spawns)}, spawn_x = {_num(s0.x)}, "
                     f"spawn_y = {_num(s0.y)}, spawn_plane = {int(s0.plane)} WHERE map_id = {mid};")
    lines.append("\nCOMMIT;\n")
    out.write_text("\n".join(lines), encoding="utf-8")
    return [out]


def bundle(profile: Profile) -> dict:
    return {
        "format": "asura-content-bundle/0",
        "profile": {"id": profile.id, "name": profile.name, "description": profile.description,
                    "based_on": profile.based_on},
        "agents": [_record_to_dict(a) for a in profile.agents],
        "dialogues": [dialogue_to_dict(d) for d in profile.dialogues],
        "quests": [quest_to_dict(q) for q in profile.quests],
        "maps": [map_to_dict(m) for _, m in sorted(profile.maps.items())],
        "scripts": {s.id: s.source for s in profile.scripts},
    }


@exporter("content_json", "Content bundle (JSON)", ".json")
def export_json(profile: Profile, out: Path) -> list[Path]:
    out.write_text(json.dumps(bundle(profile), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return [out]


def _lua_str(s: str) -> str:
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif o < 32 or o == 127:
            out.append(f"\\{o:03d}")
        else:
            out.append(ch)  # UTF-8 bytes pass through a Lua string unchanged
    out.append('"')
    return "".join(out)


def _lua_value(v, indent: int = 0) -> str:
    pad = "  " * (indent + 1)
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return _lua_str(v)
    if isinstance(v, list):
        if not v:
            return "{}"
        return "{\n" + ",\n".join(pad + _lua_value(x, indent + 1) for x in v) + "\n" + "  " * indent + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        items = []
        for k, x in v.items():
            key = k if isinstance(k, str) and k.isidentifier() else f"[{json.dumps(str(k))}]"
            items.append(f"{pad}{key} = {_lua_value(x, indent + 1)}")
        return "{\n" + ",\n".join(items) + "\n" + "  " * indent + "}"
    return json.dumps(str(v))


@exporter("lua_bundle", "Content bundle (Lua module + scripts)", ".lua")
def export_lua(profile: Profile, out: Path) -> list[Path]:
    data = bundle(profile)
    scripts = data.pop("scripts")
    out.write_text("-- Generated by ASURA Construction Set. Content data as a Lua table.\nreturn "
                   + _lua_value(data) + "\n", encoding="utf-8")
    written = [out]
    sdir = out.parent / (out.stem + "_scripts")
    sdir.mkdir(exist_ok=True)
    for sid, src in scripts.items():
        p = sdir / f"{sid}.lua"
        p.write_text(src, encoding="utf-8")
        written.append(p)
    return written


def run(key: str, profile: Profile, out: str | Path) -> list[Path]:
    return EXPORTERS[key][2](profile, Path(out))


__all__ = ["EXPORTERS", "exporter", "run", "bundle", "fields"]
