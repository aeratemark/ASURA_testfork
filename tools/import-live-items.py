#!/usr/bin/env python3
"""Fold the client item probes into the world pack.

    python tools/import-live-items.py

The probe records are the client's own answer to "what is this item?": `model_file_id`,
`model_id`, `item_type` and the coded name units. This tool reads the merged probe file and edits
`config/World/Vanilla/items.json` in one pass:

  * a curated definition whose wire identity the client has shown is marked `"live": true`;
  * every other live identity becomes a definition with a `live_<file>_<model>_<type>` id.

The definitions generated by an earlier run are rebuilt, not appended twice. `/item` accepts only
definitions with `"live": true`, because an unverified file id can be missing its UI texture.

The probe's name units are the client's coded string. When Rurik's `codedstr.py` and `textrec.py`
are present the tool also resolves a readable description; without them the description falls back
to the wire identity. The client still draws the item from the name units, so the icon does not
depend on the description.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PACK = ROOT / "config" / "World" / "Vanilla" / "items.json"
DEFAULT_PROBES = ROOT / "recordings" / "client" / "feature" / "items" / "items-live-merged.json"
TOOLKIT = ROOT / "Other_Repos_Research" / "Rurik-main" / "toolkit" / "clientscan"
GENERATED_PREFIX = "live_"
STACKABLE_TYPES = {9, 11, 30}
MAX_NAME_UNITS = 64
MAX_MODIFIERS = 64
MODIFIER_SENTINEL = 0xC0000000
EQUIP_POSITIONS = {
    1: [0], 2: [0], 5: [0], 15: [0], 22: [0], 26: [0], 27: [0], 32: [0],
    35: [0], 36: [0], 12: [1], 24: [1], 7: [2], 19: [3], 16: [4], 4: [5],
    13: [6], 44: [7], 45: [8],
}


def normal_file(value) -> int:
    return int(value) & 0x7FFFFFFF


def identity(item: dict) -> tuple[int, int, int]:
    return (
        normal_file(item.get("model_file_id", item.get("file_id", 0))),
        int(item.get("item_type", 0)),
        int(item.get("model_id", 0)),
    )


def plain_name(text: str) -> str:
    text = re.sub(r"<[^>]*>", "", text)
    text = re.sub(r"\[[^\]]*\]", "", text)
    text = re.sub(r"%[A-Za-z]+\d+%", "", text)
    text = text.replace("www.GuildWars.com", "").replace("\\n", " ")
    text = re.sub(r"\s+", " ", text).strip()
    return text


class Decoder:
    def __init__(self, exe: str | None, dat: str | None):
        self.index = None
        if not TOOLKIT.is_dir():
            return
        try:
            sys.path.insert(0, str(TOOLKIT))
            import codedstr
            import textrec

            exe = exe or os.environ.get("ASURA_GW_EXE") or r"D:\GWClone\Gw.exe"
            dat = dat or os.environ.get("ASURA_GW_DAT") or r"D:\GWClone\Gw.dat"
            self.codedstr = codedstr
            self.index = textrec.TextIndex(exe=exe, dat=dat)
        except Exception as error:  # noqa: BLE001 - the description is optional
            print(f"name decode unavailable ({type(error).__name__}: {error}); using wire ids")

    def text(self, units) -> str:
        if self.index is None or not units:
            return ""
        try:
            parts = self.codedstr.parse_coded([int(unit) for unit in units])
        except Exception:  # noqa: BLE001 - a truncated name must not stop the import
            return ""
        out = []
        for kind, value in parts:
            if kind != "id":
                continue
            text = self.index.get(value)
            if text:
                out.append(text)
        return plain_name("".join(out))

    def close(self):
        if self.index is not None:
            self.index.close()


def live_definition(item: dict, decoder: Decoder, description_seen: set[str]) -> dict:
    file_id, item_type, model_id = identity(item)
    units = [int(unit) & 0xFFFF for unit in item.get("name_enc", [])][:MAX_NAME_UNITS]
    description = decoder.text(units)
    if (
        not re.search(r"[A-Za-z0-9]", description)
        or description.lower() == "unknown"
    ):
        description = f"Live item file 0x{file_id:x} model {model_id} type {item_type}"
    if description in description_seen:
        description = f"{description} [0x{file_id:x}/{model_id}/{item_type}]"
    description_seen.add(description)

    modifiers = []
    for word in item.get("modifiers", []):
        word = int(word) & 0xFFFFFFFF
        if word != MODIFIER_SENTINEL:
            modifiers.append(word)
    if len(modifiers) > MAX_MODIFIERS:
        modifiers = modifiers[:MAX_MODIFIERS]

    quantity = int(item.get("quantity", 1) or 1)
    stackable = quantity > 1 or int(item.get("item_type", 0)) in STACKABLE_TYPES
    definition = {
        "id": f"{GENERATED_PREFIX}{file_id:x}_{model_id}_{item_type}",
        "live": True,
        "doc": (
            f"Live item from the client's item probe; file 0x{file_id:x}, "
            f"model {model_id}, type {item_type}."
        ),
        "file_id": file_id,
        "model_id": model_id,
        "item_type": int(item.get("item_type", 0)),
        "name": units,
        "description": description,
        "value": max(0, int(item.get("value", 0) or 0)),
        "materials": 0,
        "unk1": 0,
        "flags": int(item.get("interaction", 0) or 0) & 0xFFFFFFFF,
        "profession": max(0, min(255, int(item.get("profession", 0) or 0))),
        "modifiers": modifiers,
        "stackable": stackable,
        "max_stack": 250 if stackable else 1,
        "equip_positions": EQUIP_POSITIONS.get(int(item.get("item_type", 0)), []),
        "restrictions": [],
    }
    return definition


def canonical(definition: dict) -> dict:
    order = [
        "id", "live", "doc", "file_id", "model_id", "item_type", "name", "description",
        "value", "materials", "unk1", "flags", "profession", "modifiers", "stackable",
        "max_stack", "equip_positions", "restrictions", "base", "upgrades",
    ]
    return {key: definition[key] for key in order if key in definition}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pack", type=Path, default=DEFAULT_PACK)
    parser.add_argument("--probes", type=Path, default=DEFAULT_PROBES)
    parser.add_argument("--exe", default=None)
    parser.add_argument("--dat", default=None)
    args = parser.parse_args()

    pack = json.loads(args.pack.read_text(encoding="utf-8"))
    probes = json.loads(args.probes.read_text(encoding="utf-8"))
    curated = {
        identity(definition): definition
        for definition in pack["definitions"]
        if not definition.get("id", "").startswith(GENERATED_PREFIX)
    }
    probe_identities = {
        identity(item) for item in probes.get("identities", [])
    }
    for definition in pack["definitions"]:
        if definition.get("id", "").startswith(GENERATED_PREFIX):
            continue
        if identity(definition) in probe_identities:
            definition["live"] = True

    decoder = Decoder(args.exe, args.dat)
    description_seen = {definition.get("description", "") for definition in curated.values()}
    generated = []
    seen_ids = set()
    for item in probes.get("identities", []):
        key = identity(item)
        file_id, item_type, _model_id = key
        if file_id == 0 or item_type > 45:
            continue
        if key in curated:
            continue
        definition = live_definition(item, decoder, description_seen)
        if definition["id"] in seen_ids:
            continue
        seen_ids.add(definition["id"])
        generated.append(definition)
    decoder.close()

    kept = [canonical(definition) for definition in curated.values()]
    pack["definitions"] = kept + [canonical(definition) for definition in generated]
    pack["note"] = (
        "Static item definitions. An owned item is a row in t_item and may name one of these with "
        "definition_id; the row keeps the wire fields CREATE_NAMED_ITEM carries, so an old row "
        "without a definition still rebuilds its message exactly. Names are UTF-16 code units because "
        "an item name is not always a string (the backpack's is a packed Gw.dat template id). "
        '"live": true means the client item probe has shown this exact wire identity and /item may '
        "grant it."
    )
    args.pack.write_text(
        json.dumps(pack, indent=2, ensure_ascii=True) + "\n", encoding="utf-8"
    )
    print(
        f"{len(kept)} curated + {len(generated)} live definitions -> {args.pack}"
    )
    # The probe's names are the client's *display* names, composed from the base and its upgrades.
    # Split them into base + upgrades so the pack carries the bare base name the live server sends
    # (docs/50-item-framework.md, "Base + upgrade"); the world refuses to start otherwise.
    import subprocess

    split = subprocess.run(
        [sys.executable, str(ROOT / "tools" / "split-item-upgrades.py"), "--pack", str(args.pack.parent), "--write"],
        check=False,
    )
    return split.returncode


if __name__ == "__main__":
    raise SystemExit(main())
